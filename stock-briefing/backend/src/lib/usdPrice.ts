/**
 * 미국 주식 가격의 자리 — 토스증권 화면과 같이 1달러 이상은 센트 아래를 **버린다** (반올림하지 않는다).
 *
 * 공식 Open API 현재가(/api/v1/prices lastPrice)는 소수 넷째 자리까지 온다 (센트 아래 가격으로 체결된 거래: 354.555 · 34.5282).
 * 2026-11-12 실측 (같은 체결을 토스증권 화면·토스 웹소켓 체결과 대조):
 *  - 브로드컴 02:10:33 공식 354.555 → 토스 화면 체결가 $354.55 (반올림이면 $354.56)
 *  - 아이온큐 공식 34.5282 → 웹소켓 체결 34.52 (반올림이면 34.53) · 버티브 210.235 → 210.23 · 암페놀 82.405 → 82.40
 * 그대로 두면 앱이 둘째 자리로 반올림해 토스보다 1센트 높게 보이고(현재가·전일 대비), 웹소켓 체결(이미 버린 값)과 현재가 확인 값이
 * 같은 체결인데 다른 가격으로 보인다. 그래서 받는 자리에서 토스와 같은 자리로 맞춘다.
 * 1달러 미만 종목은 소수 넷째 자리까지 쓰므로 그대로 둔다 ($0.0537)
 */

/** 부동소수 오차만 메우는 여유 (센트 단위): 354.55 가 35454.99999999999 가 되어 354.54 로 버려지지 않게. 실제 값은 0.01센트 단위라 이만큼 가까운 값은 없다 */
const EPS = 1e-6;

export function truncUsdPrice(price: number): number {
  if (!Number.isFinite(price) || price < 1) return price;
  return Math.floor(price * 100 + EPS) / 100;
}
